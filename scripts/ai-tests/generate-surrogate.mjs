import { openSync, writeSync, closeSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';

const SAMPLE_RATE = 16_000;
function header(samples) {
  const bytes = samples * 2, result = Buffer.alloc(44);
  result.write('RIFF', 0); result.writeUInt32LE(36 + bytes, 4); result.write('WAVEfmt ', 8);
  result.writeUInt32LE(16, 16); result.writeUInt16LE(1, 20); result.writeUInt16LE(1, 22);
  result.writeUInt32LE(SAMPLE_RATE, 24); result.writeUInt32LE(SAMPLE_RATE * 2, 28);
  result.writeUInt16LE(2, 32); result.writeUInt16LE(16, 34); result.write('data', 36); result.writeUInt32LE(bytes, 40);
  return result;
}
/** Deterministic integer pulses. These are NOT speech or evidence of Silero accuracy. */
export function writePcm(path, samples, mode = 'silence') {
  if (!Number.isSafeInteger(samples) || samples < 1 || samples > 6 * 3600 * SAMPLE_RATE || !['silence', 'surrogate'].includes(mode)) throw new Error('Invalid bounded PCM fixture parameters');
  const fd = openSync(path, 'wx'), hash = createHash('sha256');
  const append = bytes => { let offset = 0; while (offset < bytes.length) offset += writeSync(fd, bytes, offset); hash.update(bytes); };
  try {
    append(header(samples));
    const block = Buffer.alloc(SAMPLE_RATE * 2);
    for (let start = 0; start < samples; start += SAMPLE_RATE) {
      const length = Math.min(SAMPLE_RATE, samples - start);
      block.fill(0);
      if (mode === 'surrogate') for (let i = 0; i < length; i++) {
        const position = start + i;
        // Four seconds of pulses, then two seconds of exact silence. Integer-only
        // generation gives identical samples across machines and Node versions.
        if (Math.floor(position / SAMPLE_RATE) % 6 < 4) block.writeInt16LE((position % 73 < 36 ? 1 : -1) * (2000 + position % 997), i * 2);
      }
      append(block.subarray(0, length * 2));
    }
  } finally { closeSync(fd); }
  return { path, sha256: hash.digest('hex'), sampleRate: SAMPLE_RATE, channels: 1, samples, durationMs: samples * 1000 / SAMPLE_RATE, byteLength: 44 + samples * 2, classification: mode === 'silence' ? 'silence' : 'non-speech-surrogate', license: 'GPL-3.0-or-later', source: 'Original deterministic PCM generated by Surtitle; no external TTS or speech asset' };
}
export function generate(directory, durationSeconds = 12) {
  if (!Number.isSafeInteger(durationSeconds) || durationSeconds < 1 || durationSeconds > 21_600) throw new Error('Duration must be 1–21600 integer seconds');
  directory = resolve(directory);
  mkdirSync(directory, { recursive: true });
  const files = [
    writePcm(join(directory, 'A01-silence-250ms.wav'), 4000),
    writePcm(join(directory, 'A01-silence-tail-16007.wav'), 16007),
    writePcm(join(directory, 'A06-non-speech-surrogate.wav'), durationSeconds * SAMPLE_RATE, 'surrogate'),
  ];
  const manifest = { schemaVersion: 1, evidenceKind: 'deterministic-non-speech-surrogate', generatedWith: 'surtitle-integer-pcm-v1', license: 'GPL-3.0-or-later', note: 'Tests sample continuity, duration, IO, cancellation and bounded memory only. Not speech, not a Silero detection oracle, and not evidence of real model quality. No cloud or TTS call was made.', files };
  writeFileSync(join(directory, 'surrogate-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`, { flag: 'wx' });
  const speech = { schemaVersion: 1, license: 'User must record applicable rights; this template grants no rights to an audio file', cases: [{ id: 'A02-en-user-01', language: 'en', evidenceKind: 'unreviewed-user-template', audio: { path: '', sha256: '', durationMs: 0, sampleRate: 16000, source: '', license: '', evaluationUsePermitted: false, redistributionPermitted: false, classification: 'speech', annotator: '', independentReviewer: '', reviewedAt: '' }, cues: [], boundaries: [] }], instructions: 'Provide authorized audio and SHA-256, exact duration, manually transcribed cues {id,startMs,endMs,text}, and independent timing/text review. Set evidenceKind to human-reviewed-reference only after review. Boundary annotations require 20 or more IDs with exact text; never qualify a model using generated surrogate PCM.' };
  writeFileSync(join(directory, 'user-speech-manifest.template.json'), `${JSON.stringify(speech, null, 2)}\n`, { flag: 'wx' });
  return manifest;
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const args = process.argv.slice(2);
    if (args.length === 1 && args[0] === '--help') process.stdout.write('node scripts/ai-tests/generate-surrogate.mjs --output-dir DIRECTORY [--duration-seconds 12]\nGenerates original non-speech PCM, never TTS or cloud audio. Maximum 21600 seconds (six hours); output files must not exist.\n');
    else {
      if (![2, 4].includes(args.length) || args[0] !== '--output-dir' || args.length === 4 && args[2] !== '--duration-seconds') throw new Error('Use --output-dir DIRECTORY [--duration-seconds INTEGER]');
      const result = generate(args[1], args[3] === undefined ? 12 : Number(args[3]));
      process.stdout.write(`${JSON.stringify({ files: result.files.length, cloudRequests: 0, speechQualityAssessed: false })}\n`);
    }
  } catch (error) { process.stderr.write(`Fixture generation failed: ${error.message}\n`); process.exitCode = 1; }
}
