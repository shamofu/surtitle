import { expect, test } from '@playwright/test';
import { installLearningFixture } from './learning-fixture';

test('retains separate provider budgets, key state and model settings across navigation', async ({ page }) => {
  await installLearningFixture(page, 'en', 'light');
  await page.goto('/settings#ai');
  const provider = page.getByRole('combobox', { name: /^AI provider/ });
  const monthly = page.getByRole('textbox', { name: /^Monthly AI budget/ });
  await monthly.fill('5');
  await provider.focus();
  await expect.poll(() => page.evaluate(() => (window as any).__learningFixture.snapshot.settings.monthlyBudgetUsd)).toBe(5);
  const budgetProvider = page.getByRole('combobox', { name: /^Budget provider/ });
  await budgetProvider.selectOption('openai');
  await monthly.fill('8'); await budgetProvider.focus();
  await expect.poll(() => page.evaluate(() => (window as any).__learningFixture.snapshot.settings.openai.monthlyBudgetUsd)).toBe(8);
  await expect(provider).toHaveValue('vertex');
  expect(await page.evaluate(() => (window as any).__learningFixture.snapshot.settings.aiModels)).toEqual({});
  await provider.selectOption('openai');
  await expect(monthly).toHaveValue('8');
  await page.getByLabel('OpenAI API key', { exact: true }).fill('fixture-only-key');
  await page.getByRole('button', { name: 'Save API key', exact: true }).click();
  await expect(page.getByLabel('OpenAI API key', { exact: true })).toHaveValue('');
  await expect(page.getByText('API key configured', { exact: true })).toBeVisible();
  await monthly.fill('8'); await provider.focus();
  await expect.poll(() => page.evaluate(() => (window as any).__learningFixture.snapshot.settings.openai.monthlyBudgetUsd)).toBe(8);
  await page.getByRole('button', { name: 'Fetch OpenAI model candidates' }).click();
  await page.getByText('Detailed settings by purpose', { exact: true }).click();
  const models = page.getByRole('combobox', { name: 'OpenAI model ID', exact: true });
  await models.nth(0).fill('gpt-fixture-transcribe');
  await provider.focus();
  await expect.poll(() => page.evaluate(() => (window as any).__learningFixture.snapshot.settings.openai.aiModels.transcription.modelId)).toBe('gpt-fixture-transcribe');
  await provider.selectOption('vertex');
  await budgetProvider.selectOption('vertex');
  await expect(monthly).toHaveValue('5');
  await provider.selectOption('openai');
  await budgetProvider.selectOption('openai');
  await expect(monthly).toHaveValue('8');
  await expect(models.nth(0)).toHaveValue('gpt-fixture-transcribe');
  await page.reload();
  await expect(provider).toHaveValue('openai');
  await expect(monthly).toHaveValue('8');
  await page.getByRole('button', { name: 'Remove API key', exact: true }).click();
  await expect(page.getByText('No API key configured', { exact: true })).toBeVisible();
});
